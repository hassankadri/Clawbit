"""Idempotent schema for Clawbit's fresh Neon PostgreSQL database.

Only the stores migrated to PostgreSQL are created here. Additional application
stores are added in separate, reviewed migrations.
"""

SCHEMA_STATEMENTS = (
    "CREATE EXTENSION IF NOT EXISTS citext",
    """
    CREATE TABLE IF NOT EXISTS owner (
        id BIGINT PRIMARY KEY CHECK (id = 1),
        username TEXT NOT NULL UNIQUE,
        password_hash TEXT NOT NULL,
        created_at DOUBLE PRECISION NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS owner_identity (
        owner_id BIGINT PRIMARY KEY REFERENCES owner(id),
        principal_id TEXT NOT NULL UNIQUE
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS users (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        username CITEXT NOT NULL UNIQUE,
        email CITEXT UNIQUE,
        password_hash TEXT NOT NULL,
        role TEXT NOT NULL DEFAULT 'user' CHECK (role IN ('admin', 'user')),
        created_at DOUBLE PRECISION NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS user_identity (
        user_id BIGINT PRIMARY KEY REFERENCES users(id),
        principal_id TEXT NOT NULL UNIQUE
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS sessions (
        token_hash TEXT PRIMARY KEY,
        owner_id BIGINT REFERENCES users(id),
        expires_at DOUBLE PRECISION NOT NULL
    )
    """,
    "CREATE INDEX IF NOT EXISTS session_expiration ON sessions(expires_at)",
    """
    CREATE TABLE IF NOT EXISTS login_attempts (
        scope TEXT NOT NULL,
        bucket TEXT NOT NULL,
        window_started DOUBLE PRECISION NOT NULL,
        attempts INTEGER NOT NULL,
        PRIMARY KEY (scope, bucket)
    )
    """,
    "CREATE INDEX IF NOT EXISTS login_attempt_expiration ON login_attempts(window_started)",
    """
    CREATE TABLE IF NOT EXISTS setup_tokens (
        id INTEGER PRIMARY KEY CHECK (id = 1),
        token_hash TEXT NOT NULL,
        issued_at DOUBLE PRECISION NOT NULL,
        expires_at DOUBLE PRECISION NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS resources (
        kind TEXT NOT NULL CHECK (kind IN ('thread', 'workspace')),
        resource_id TEXT NOT NULL,
        principal_id TEXT,
        PRIMARY KEY (kind, resource_id)
    )
    """,
    "CREATE INDEX IF NOT EXISTS resource_principal_lookup ON resources(kind, principal_id)",
    """
    CREATE TABLE IF NOT EXISTS workspaces (
        id TEXT PRIMARY KEY,
        name TEXT NOT NULL DEFAULT 'Default Workspace',
        created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS conversations (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        thread_id TEXT UNIQUE,
        workspace_id TEXT,
        title TEXT NOT NULL DEFAULT 'New Chat',
        created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP,
        updated_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
    """,
    "CREATE INDEX IF NOT EXISTS conversations_thread_id_idx ON conversations(thread_id)",
    "CREATE INDEX IF NOT EXISTS conversations_workspace_id_idx ON conversations(workspace_id)",
    """
    CREATE TABLE IF NOT EXISTS chat_messages (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        thread_id TEXT NOT NULL,
        workspace_id TEXT,
        role TEXT NOT NULL,
        content TEXT NOT NULL,
        created_at TIMESTAMP WITHOUT TIME ZONE NOT NULL DEFAULT CURRENT_TIMESTAMP
    )
    """,
    "CREATE INDEX IF NOT EXISTS chat_messages_thread_id_idx ON chat_messages(thread_id)",
    """
    CREATE TABLE IF NOT EXISTS history_schema (
        version INTEGER NOT NULL
    )
    """,
    "INSERT INTO history_schema(version) SELECT 1 WHERE NOT EXISTS (SELECT 1 FROM history_schema)",
    """
    CREATE TABLE IF NOT EXISTS history_conversations (
        thread_id TEXT PRIMARY KEY,
        workspace_id TEXT NOT NULL,
        display_id TEXT NOT NULL,
        title TEXT NOT NULL,
        pinned BOOLEAN NOT NULL DEFAULT FALSE,
        model TEXT NOT NULL,
        mode TEXT NOT NULL,
        created_at BIGINT NOT NULL,
        updated_at BIGINT NOT NULL,
        version BIGINT NOT NULL DEFAULT 0,
        deleted BOOLEAN NOT NULL DEFAULT FALSE,
        active_revision TEXT
    )
    """,
    "CREATE INDEX IF NOT EXISTS history_updated ON history_conversations(updated_at DESC, thread_id)",
    "CREATE INDEX IF NOT EXISTS history_workspace ON history_conversations(workspace_id, updated_at DESC)",
    """
    CREATE TABLE IF NOT EXISTS history_revisions (
        id TEXT PRIMARY KEY,
        thread_id TEXT NOT NULL REFERENCES history_conversations(thread_id),
        parent_id TEXT REFERENCES history_revisions(id),
        request_id TEXT NOT NULL,
        fingerprint TEXT NOT NULL,
        operation TEXT NOT NULL,
        state TEXT NOT NULL,
        messages TEXT NOT NULL,
        created_at BIGINT NOT NULL,
        checkpoint_id TEXT,
        UNIQUE(thread_id, request_id)
    )
    """,
    "CREATE INDEX IF NOT EXISTS history_revision_thread ON history_revisions(thread_id, created_at DESC)",
    """
    CREATE TABLE IF NOT EXISTS memory_schema (
        version INTEGER NOT NULL
    )
    """,
    "INSERT INTO memory_schema(version) SELECT 1 WHERE NOT EXISTS (SELECT 1 FROM memory_schema)",
    """
    CREATE TABLE IF NOT EXISTS long_term_memory (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        thread_id TEXT,
        memory TEXT,
        created_at TIMESTAMP WITHOUT TIME ZONE DEFAULT CURRENT_TIMESTAMP,
        workspace_id TEXT
    )
    """,
    "CREATE INDEX IF NOT EXISTS memory_workspace_lookup ON long_term_memory(workspace_id, id)",
    """
    CREATE TABLE IF NOT EXISTS memory_details (
        memory_id BIGINT PRIMARY KEY REFERENCES long_term_memory(id),
        scope TEXT NOT NULL,
        version BIGINT NOT NULL DEFAULT 0,
        deleted SMALLINT NOT NULL DEFAULT 0,
        updated_at BIGINT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS memory_audit (
        id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
        memory_id BIGINT NOT NULL,
        principal TEXT NOT NULL,
        action TEXT NOT NULL,
        created_at BIGINT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS usage (
        principal TEXT NOT NULL,
        operation TEXT NOT NULL,
        period BIGINT NOT NULL,
        window BIGINT NOT NULL,
        count BIGINT NOT NULL,
        PRIMARY KEY (principal, operation, period, window)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS leases (
        id TEXT PRIMARY KEY,
        principal TEXT NOT NULL,
        operation TEXT NOT NULL,
        expires_at DOUBLE PRECISION NOT NULL
    )
    """,
    "CREATE INDEX IF NOT EXISTS leases_expiration ON leases(expires_at)",
    "CREATE INDEX IF NOT EXISTS leases_operation ON leases(operation, expires_at)",
    """
    CREATE TABLE IF NOT EXISTS connector_epochs (
        principal TEXT NOT NULL,
        provider TEXT NOT NULL,
        generation BIGINT NOT NULL,
        PRIMARY KEY (principal, provider)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS credentials (
        principal TEXT NOT NULL,
        provider TEXT NOT NULL,
        epoch BIGINT NOT NULL,
        ciphertext BYTEA NOT NULL,
        PRIMARY KEY (principal, provider)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS oauth_states (
        state TEXT PRIMARY KEY,
        principal TEXT NOT NULL,
        provider TEXT NOT NULL,
        session_id TEXT NOT NULL,
        version BIGINT NOT NULL,
        redirect_uri TEXT NOT NULL,
        connection_epoch BIGINT NOT NULL,
        verifier TEXT NOT NULL,
        created_at DOUBLE PRECISION NOT NULL,
        expires_at DOUBLE PRECISION NOT NULL,
        frontend_url TEXT NOT NULL
    )
    """,
    "CREATE INDEX IF NOT EXISTS oauth_states_owner_expiry ON oauth_states(principal, expires_at)",
    """
    CREATE TABLE IF NOT EXISTS pending_approvals (
        id TEXT PRIMARY KEY,
        owner TEXT NOT NULL,
        provider TEXT NOT NULL,
        tool TEXT NOT NULL,
        arguments TEXT NOT NULL,
        created_at DOUBLE PRECISION NOT NULL,
        expires_at DOUBLE PRECISION NOT NULL,
        decision BOOLEAN,
        decided_at DOUBLE PRECISION
    )
    """,
    "CREATE INDEX IF NOT EXISTS pending_approvals_owner_expiry ON pending_approvals(owner, expires_at)",
    "CREATE EXTENSION IF NOT EXISTS vector",
    """
    CREATE TABLE IF NOT EXISTS rag_documents (
        id TEXT PRIMARY KEY,
        principal TEXT NOT NULL,
        thread_id TEXT NOT NULL,
        attachment_id TEXT NOT NULL,
        content TEXT NOT NULL,
        embedding vector(3072) NOT NULL,
        metadata JSONB NOT NULL
    )
    """,
    "CREATE INDEX IF NOT EXISTS rag_documents_owner_thread ON rag_documents(principal,thread_id,attachment_id)",
    """
    CREATE TABLE IF NOT EXISTS upload_attachments (
        principal TEXT NOT NULL,
        thread_id TEXT NOT NULL,
        attachment_id TEXT NOT NULL,
        name TEXT NOT NULL,
        kind TEXT NOT NULL,
        mime_type TEXT NOT NULL,
        size BIGINT NOT NULL,
        object_key TEXT NOT NULL UNIQUE,
        source TEXT NOT NULL,
        preview TEXT,
        rag_error TEXT,
        created_at DOUBLE PRECISION NOT NULL,
        PRIMARY KEY (principal,thread_id,attachment_id)
    )
    """,
    "CREATE INDEX IF NOT EXISTS upload_attachments_thread ON upload_attachments(principal,thread_id,created_at)",
    """
    CREATE TABLE IF NOT EXISTS upload_intents (
        attachment_id TEXT NOT NULL,
        principal TEXT NOT NULL,
        thread_id TEXT NOT NULL,
        staging_key TEXT NOT NULL UNIQUE,
        final_key TEXT UNIQUE,
        name TEXT NOT NULL,
        suffix TEXT NOT NULL,
        mime_type TEXT NOT NULL,
        kind TEXT NOT NULL CHECK (kind IN ('document','image')),
        expected_size BIGINT NOT NULL CHECK (expected_size > 0),
        created_at DOUBLE PRECISION NOT NULL,
        expires_at DOUBLE PRECISION NOT NULL,
        PRIMARY KEY (principal,thread_id,attachment_id)
    )
    """,
    "CREATE INDEX IF NOT EXISTS upload_intents_expiration ON upload_intents(principal,expires_at)",
    """
    CREATE TABLE IF NOT EXISTS claims (
        claim_id TEXT PRIMARY KEY,
        principal_id TEXT NOT NULL,
        created_at DOUBLE PRECISION NOT NULL,
        resource_count INTEGER NOT NULL,
        backup_path TEXT NOT NULL
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS claim_resources (
        claim_id TEXT NOT NULL,
        kind TEXT NOT NULL,
        resource_id TEXT NOT NULL,
        PRIMARY KEY (claim_id, kind, resource_id)
    )
    """,
    """
    CREATE TABLE IF NOT EXISTS rollbacks (
        claim_id TEXT PRIMARY KEY,
        created_at DOUBLE PRECISION NOT NULL,
        backup_path TEXT NOT NULL
    )
    """,
)
